require 'json'
require 'shellwords'

# Shared by CocoaPods and the project generator. Apply with `pod install` after editing JSON.
module WristNotesBuildFeatures
  FLAG = 'WISELIFE_EUREKA_RING'.freeze
  SOURCES = {
    'WristNotes' => %w[EurekaRingModel.swift RingTransferStore.swift],
    'RingIntegrationTests' => %w[RingIntegrationTests.swift]
  }.freeze

  def self.enabled?(root)
    value = JSON.parse(File.read(File.join(root, 'Config/BuildFeatures.json'))).fetch('eurekaRing')
    raise ArgumentError, 'eurekaRing must be true or false' unless value == true || value == false
    value
  end

  def self.apply(project, enabled:)
    project.targets.each do |target|
      sources = SOURCES[target.name]
      next unless sources
      target.build_configurations.each do |configuration|
        settings = configuration.build_settings
        flags = tokens(settings['SWIFT_ACTIVE_COMPILATION_CONDITIONS']) - [FLAG]
        flags.unshift('$(inherited)') unless flags.include?('$(inherited)')
        flags << FLAG if enabled
        settings['SWIFT_ACTIVE_COMPILATION_CONDITIONS'] = flags.uniq
        excluded = tokens(settings['EXCLUDED_SOURCE_FILE_NAMES']) - sources
        excluded.unshift('$(inherited)') unless excluded.include?('$(inherited)')
        excluded.concat(sources) unless enabled
        settings['EXCLUDED_SOURCE_FILE_NAMES'] = excluded.uniq
        settings['WISELIFE_EUREKA_RING_ENABLED'] = enabled ? 'YES' : 'NO'
        if target.name == 'RingIntegrationTests'
          # Native already copies Opus. A second Pod target would produce the
          # same XCFramework output twice; tests only need the encoder linked.
          linker = tokens(settings['OTHER_LDFLAGS'])
          while (index = linker.each_cons(2).find_index { |pair| pair == %w[-framework BRRecorderOpus] })
            linker.slice!(index, 2)
          end
          linker.unshift('$(inherited)') unless linker.include?('$(inherited)')
          linker.concat(%w[-framework BRRecorderOpus]) if enabled
          settings['OTHER_LDFLAGS'] = linker
        end
      end
    end
  end

  def self.tokens(value)
    value.is_a?(Array) ? value.dup : Shellwords.split(value.to_s)
  end

  # Script outputs grant access to exact paths, not directory contents. Derive
  # the Ring bundles' flat resource files from CocoaPods rather than duplicating
  # the privacy/license manifest here. Info.plist is generated by each target.
  def self.prepare_resource_outputs(project, pods_project:)
    bundles = pods_project.native_targets.each_with_object({}) do |target, result|
      next unless target.product_type == 'com.apple.product-type.bundle'
      next unless target.name.start_with?('br_flutter_plugin_ble-')
      result[target.product_reference.path] = ['Info.plist'] + target.resources_build_phase.files_references.map { |file| File.basename(file.path) }
    end
    project.native_targets.each do |target|
      target.shell_script_build_phases.each do |phase|
        next unless phase.name == '[CP] Copy Pods Resources'
        phase.output_paths = phase.output_paths.flat_map do |path|
          files = bundles[File.basename(path)]
          files ? [path.delete_suffix('/')] + files.map { |file| File.join(path, file) } : [path]
        end.uniq
      end
    end
  end

  # CocoaPods 1.16 writes a transient resource list into the source Pods folder.
  # Xcode allows TEMP_DIR, but explicitly denies its DerivedSources child unless
  # declared as an output. This list is removed by the script, so keep it in
  # TEMP_DIR. Also migrate scripts patched by the earlier DERIVED_FILE_DIR fix.
  def self.prepare_resource_scripts(root)
    Dir.glob(File.join(root, 'Pods/Target Support Files/Pods-*/*-resources.sh')).each do |path|
      source = File.read(path)
      updated = source.gsub(/RESOURCES_TO_COPY=\$\{(?:PODS_ROOT|DERIVED_FILE_DIR)\}\/resources-to-copy-/,
                            'RESOURCES_TO_COPY=${TEMP_DIR}/resources-to-copy-')
      # rsync's random temporary filenames cannot be declared as build outputs.
      # Stage them in TEMP_DIR, then rename to the declared destination files.
      updated = updated.gsub('rsync -avr --copy-links', 'rsync -avr --temp-dir="${TEMP_DIR}" --copy-links')
      File.write(path, updated) if updated != source
    end
  end
end
